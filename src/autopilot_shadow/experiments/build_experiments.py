"""
Day 15 — runs Experiments A-E (Section 30) and writes the real result to
`results/day15_experiments.json` (S7: generated by running real code).

Run: python -m autopilot_shadow.experiments.build_experiments
"""

from __future__ import annotations

import json
from pathlib import Path

from .engine import run_all

RESULTS_DIR = Path(__file__).resolve().parents[3] / "results"


def build() -> list[dict]:
    results = run_all()
    RESULTS_DIR.mkdir(exist_ok=True)
    (RESULTS_DIR / "day15_experiments.json").write_text(json.dumps(results, indent=2, default=str))
    return results


if __name__ == "__main__":
    results = build()
    print(f"{'Exp':<4}{'Name':<38}{'Coverage':>10}{'HumanInt':>10}{'Errors':>8}{'FalseAuto':>11}{'Completion':>12}")
    for r in results:
        m = r["metrics"]
        print(
            f"{r['experiment']:<4}{r['name']:<38}{m['automation_coverage_pct']:>9}%"
            f"{m['human_interventions_pct']:>9}%{m['errors']:>8}{m['false_automation']:>11}"
            f"{m['workflow_completion_pct']:>11}%"
        )
    print("\nWrote: results/day15_experiments.json")
